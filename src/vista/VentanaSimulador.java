    // ---------- IVistaSimulador ----------
    @Override
    public void mostrarContadores(int turno, int turnosTotales, String clima, int plantas, int conejos, int lobos) {
        lblTurno.setText("Turno " + turno + " de " + turnosTotales);
        pbTurno.setMaximum(Math.max(1, turnosTotales));
        pbTurno.setValue(turno);
        lblClima.setText(clima);
        lblCantPlantas.setText(String.valueOf(plantas));
        lblCantConejos.setText(String.valueOf(conejos));
        lblCantLobos.setText(String.valueOf(lobos));
    }

    @Override
    public void mostrarEntidades(Object[][] filas) {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblEntidades.getModel();
        modelo.setRowCount(0);
        for (Object[] fila : filas) modelo.addRow(fila);
    }

    @Override
    public void mostrarEventos(java.util.List<String> eventos) {
        lstEventos.setListData(eventos.toArray(new String[0]));
    }

    @Override public void mostrarMensajeEstado(String mensaje) { lblAyuda.setText(mensaje); }

    @Override
    public void mostrarReporte(String[][] filas) {
        StringBuilder sb = new StringBuilder();
        for (String[] fila : filas) sb.append(fila[0]).append(": ").append(fila[1]).append("\n");
        javax.swing.JOptionPane.showMessageDialog(this, sb.toString(), "Reporte final",
                javax.swing.JOptionPane.INFORMATION_MESSAGE);
    }

    @Override public void habilitarAvance(boolean habilitado) { btnAvanzar.setEnabled(habilitado); }

    @Override
    public void habilitarIntervencion(boolean habilitada) {
        cmbClimas.setEnabled(habilitada);
        btnCambiarclima.setEnabled(habilitada);
        cmbAnimales.setEnabled(habilitada);
        txtCantidad.setEnabled(habilitada);
        btnAgregar.setEnabled(habilitada);
    }

    @Override
    public void habilitarCantidad(boolean habilitada, String ayuda) {
        txtCantidad.setEnabled(habilitada);
        btnAgregar.setEnabled(habilitada);
        lblAyuda.setText(ayuda);
    }

    @Override public void limpiarCantidad() { txtCantidad.setText(""); }


