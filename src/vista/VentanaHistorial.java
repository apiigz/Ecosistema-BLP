    private controlador.ControladorSimulacion controlador;
    private String categoriaActual = "Todos";   // filtro de categoría elegido

    public void setControlador(controlador.ControladorSimulacion controlador) {
        this.controlador = controlador;
    }

    private void elegirCategoria(String categoria) {
        categoriaActual = categoria;
        aplicarFiltro();
    }

    private void aplicarFiltro() {
        controlador.filtrarHistorial(categoriaActual, txtBuscar.getText(),
                txtTurnodesde.getText(), txtTurnohasta.getText());
    }

    // ---------- IVista ----------
    @Override public void mostrarVentana() { setLocationRelativeTo(null); setVisible(true); }
